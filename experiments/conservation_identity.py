"""T15-c: does §30's identity need CONSERVATION structure, or EXCHANGE SYMMETRY?

§30 found that for every n, gamma and pair (i,j) of committed species in the AM family,

    d(n_i - n_j)/dt = (n_i - n_j) * (k/Omega) * [ n_B - sum_{l!=i,j} n_l
                                                  - gamma*(n_i + n_j - 1) ]

so the deterministic flow can amplify or contract a lead but never REVERSE one, and every
error is a fluctuation in a difference direction. §31 then showed the identity breaks in
`am_asymmetric`, where the tilt beta gives X and Y different rate constants.

**THE OPEN QUESTION IS WHICH FEATURE IT ACTUALLY NEEDS**, and the AM family cannot answer
it, because there every network has exactly ONE conservation law (X+Y+B = Omega). Physical
networks carry several at once -- charge, baryon number, lepton number -- so the question
is not idle: if the identity is a fact about conservation structure it will not survive
them, and §30's "restoration" reading is much narrower than it sounds.

**READING THE CANCELLATIONS SUGGESTS THE ANSWER IS SYMMETRY, NOT CONSERVATION.** §30's
identity survives because (a) the pair's own disagreement reaction consumes both equally,
(b) its reverse reaches both through the same channels, and (c) each recruitment is linear
in the species it recruits, **with the same coefficient for i and j**. Only (c) mentions
the rate law, and it is exactly what beta breaks in §31. Nothing in the derivation counts
conservation laws.

THE TEST. Six networks crossing the two features. The cofactor family adds conserved
partner pairs that are consumed and regenerated by the reactions themselves -- so the extra
conservation laws are not decorative, they constrain the very reactions that move the
signal:

  A  `am_reversible`                1 law,  symmetric                       [control]
  B  cofactor D/E on BOTH recruitments: B + X + D -> 2X + E and its mirror.
                                    **2 laws** (X+Y+B, D+E), symmetric      [THE TEST]
  C  B plus a second cofactor F/G on the disagreement pair too.
                                    **3 laws**, symmetric                   [THE TEST]
  D  B, but Y's recruitment carries a rate tilt beta.  2 laws, symmetry broken
     by the RATE only -- same reactions, same orders, same conservation laws as B.
  E  B, but the cofactor couples to X's recruitment only.  2 laws, symmetry broken
     STRUCTURALLY.
  F  `am_asymmetric`                1 law,  symmetry broken                 [control]

The probe is §30's own: hold everything fixed, hold n_i + n_j fixed, vary the SPLIT, and
check that d(n_i - n_j)/dt divided by (n_i - n_j) does not move. That tests the identity
without needing to guess the modified bracket, which for B and C is no longer §30's.

PREDICTIONS, written before running:

  P1  GATE. A holds to machine precision and F fails, reproducing §30 and §31. If either
      misbehaves the harness is wrong and nothing below is admissible.
  P2  THE TEST. **B and C HOLD** -- the identity survives two and three conservation laws,
      with the bracket picking up the cofactor counts where §30 had constants. Recruitment
      becomes k*n_B*n_X*n_D/Omega^2, still LINEAR in n_X, so the difference stays
      proportional to it however many conserved partners ride along.
  P3  **D and E FAIL** -- breaking exchange symmetry breaks the identity at unchanged
      conservation structure. D is the sharp one: it differs from B in a single rate
      constant, so nothing structural is available as an alternative explanation.
  P4  If P2 and P3 both hold, the general statement is that **§30's identity depends on
      EXCHANGE SYMMETRY between the paired species, not on the number of conservation
      laws** -- which §29/§30/§31 circled without being able to separate. It would extend
      the claim to any network with symmetric competing autocatalysis, however many
      charges it conserves.
  P5  If instead B or C FAILS, the identity is a fact about single-conservation-law
      networks, §30's reading is narrower than stated, and a multi-charge network would
      not restore in this sense at all. Which of B/C fails localises it: B failing means
      one extra law is already too many; C-only failing means the disagreement channel is
      the fragile one.
  P6  SECONDARY. Where the identity holds, the implied bracket read off at delta -> 0
      should be a rational function of the cofactor counts, not a constant. Reported so
      that a "holds" verdict cannot be confused with "nothing changed".
"""
from __future__ import annotations

import argparse
import json
import pathlib

import numpy as np

from crnl.networks.am_asymmetric import am_asymmetric
from crnl.networks.am_reversible import am_reversible
from crnl.reactions import Reaction, ReactionNetwork


def am_cofactor(gamma: float, k: float = 1.0, beta: float = 0.0,
                x_only: bool = False, double: bool = False) -> ReactionNetwork:
    """AM whose recruitments consume a conserved cofactor D and regenerate it as E.

    Conservation laws: X+Y+B and D+E -- two, independent, and both constrain reactions
    that move the signal. `double` adds a second pair F/G on the disagreement channel
    (three laws). `beta` tilts Y's recruitment rate only; `x_only` removes the cofactor
    from Y's recruitment. Those two break exchange symmetry -- by rate and by structure
    respectively -- while leaving the conservation structure exactly as it was.
    """
    species = ["X", "Y", "B", "D", "E"]
    if double:
        dis_l, dis_r = {"X": 1, "Y": 1, "F": 1}, {"B": 2, "G": 1}
        species += ["F", "G"]
    else:
        dis_l, dis_r = {"X": 1, "Y": 1}, {"B": 2}
    rx = [
        Reaction(dis_l, dis_r, k, name="dis"),
        Reaction(dis_r, dis_l, gamma * k, name="rev-dis"),
        Reaction({"B": 1, "X": 1, "D": 1}, {"X": 2, "E": 1}, k, name="rec-X"),
        Reaction({"X": 2, "E": 1}, {"B": 1, "X": 1, "D": 1}, gamma * k, name="rev-rec-X"),
    ]
    ky = k * (1.0 + beta)
    if x_only:
        rx += [
            Reaction({"B": 1, "Y": 1}, {"Y": 2}, ky, name="rec-Y"),
            Reaction({"Y": 2}, {"B": 1, "Y": 1}, gamma * ky, name="rev-rec-Y"),
        ]
    else:
        rx += [
            Reaction({"B": 1, "Y": 1, "D": 1}, {"Y": 2, "E": 1}, ky, name="rec-Y"),
            Reaction({"Y": 2, "E": 1}, {"B": 1, "Y": 1, "D": 1}, gamma * ky,
                     name="rev-rec-Y"),
        ]
    tag = f"g{gamma}-b{beta}{'-xonly' if x_only else ''}{'-2cof' if double else ''}"
    return ReactionNetwork(species=species, reactions=rx, name=f"am-cofactor-{tag}")


def n_conservation_laws(net: ReactionNetwork) -> int:
    """dim of the left null space of S -- how many independent conserved quantities."""
    S = net.stoichiometry_matrix().astype(float)
    return int(S.shape[0] - np.linalg.matrix_rank(S))


def split_spread(net, counts, omega, i=0, j=1):
    """§30's probe: vary the (i,j) split at fixed n_i+n_j; the ratio must not move.

    Returns (relative spread of the ratio, mean ratio) or None if too few usable splits.
    """
    cs = net.stochastic_constants(float(omega))
    S = net.stoichiometry_matrix().astype(np.int64)
    total = int(counts[i] + counts[j])
    ratios = []
    for s in range(2, total - 1):
        if 2 * s == total:
            continue
        c = np.array(counts, dtype=np.int64)
        c[i], c[j] = s, total - s
        a = net.propensities(c, cs)
        b = S @ a
        ratios.append(float(b[i] - b[j]) / float(c[i] - c[j]))
    if len(ratios) < 4:
        return None
    r = np.array(ratios)
    return float(np.ptp(r) / max(abs(r.mean()), 1e-300)), float(r.mean())


def random_state(net, rng, omega):
    """Split Omega over X,Y,B; give each conserved cofactor pair its own pool."""
    cuts = np.sort(rng.integers(4, omega - 4, size=2))
    c = [int(cuts[0]), int(cuts[1] - cuts[0]), int(omega - cuts[1])]
    if min(c) < 4:
        return None
    for _ in range((len(net.species) - 3) // 2):
        d = int(rng.integers(2, omega))
        c += [d, omega - d]
    return c


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--gamma", type=float, default=0.25)
    ap.add_argument("--beta", type=float, default=0.20)
    ap.add_argument("--omega", type=int, default=90)
    ap.add_argument("--states", type=int, default=30)
    ap.add_argument("--seed", type=int, default=20260809)
    ap.add_argument("--out", type=pathlib.Path,
                    default=pathlib.Path("results/conservation_identity.json"))
    args = ap.parse_args()

    g, om, be = args.gamma, args.omega, args.beta
    rng = np.random.default_rng(args.seed)

    nets = [
        ("A", "am_reversible", am_reversible(g), "symmetric", "control: must HOLD"),
        ("B", "cofactor D/E", am_cofactor(g), "symmetric", "THE TEST"),
        ("C", "cofactor D/E + F/G", am_cofactor(g, double=True), "symmetric", "THE TEST"),
        ("D", f"cofactor, beta={be} on Y", am_cofactor(g, beta=be), "RATE broken",
         "same laws as B"),
        ("E", "cofactor on X only", am_cofactor(g, x_only=True), "STRUCT broken",
         "same laws as B"),
        ("F", "am_asymmetric", am_asymmetric(g, be), "RATE broken", "control: must FAIL"),
    ]

    print(f"gamma={g} beta={be} Omega={om}   probe: vary the X/Y split at fixed X+Y")
    print(f"{'':>2}{'network':>24}{'spc':>5}{'laws':>6}{'exchange':>15}"
          f"{'worst spread':>15}{'identity':>10}{'bracket range':>26}")
    rows = []
    for tag, label, net, sym, note in nets:
        ncl = n_conservation_laws(net)
        worst, brackets, n_ok = 0.0, [], 0
        for _ in range(args.states):
            c = random_state(net, rng, om)
            if c is None:
                continue
            res = split_spread(net, c, om)
            if res is None:
                continue
            sp, mean = res
            worst = max(worst, sp)
            brackets.append(mean)
            n_ok += 1
        holds = worst < 1e-12
        br = np.array(brackets)
        rows.append({"tag": tag, "network": label, "species": len(net.species),
                     "cons_laws": ncl, "exchange": sym, "worst_spread": worst,
                     "holds": bool(holds), "n_states": n_ok,
                     "bracket_min": float(br.min()), "bracket_max": float(br.max()),
                     "note": note})
        print(f"{tag:>2}{label:>24}{len(net.species):>5}{ncl:>6}{sym:>15}"
              f"{worst:>15.3e}{'HOLDS' if holds else 'FAILS':>10}"
              f"{br.min():>13.4f}{br.max():>13.4f}")

    by = {r["tag"]: r for r in rows}
    ok = lambda t: by[t]["holds"]

    print("\n=== P1 gate: controls")
    gate = ok("A") and not ok("F")
    print(f"  A (1 law, symmetric) {'HOLDS' if ok('A') else 'FAILS'};"
          f"  F (1 law, rate-broken) {'HOLDS' if ok('F') else 'FAILS'}"
          f"   -> {'gate OK' if gate else 'GATE FAILED -- nothing below is admissible'}")

    print("\n=== P2: does the identity survive extra conservation laws?")
    for t in ("B", "C"):
        print(f"  {t}: {by[t]['cons_laws']} laws, exchange-symmetric  -> "
              f"{'HOLDS' if ok(t) else 'FAILS'}  (spread {by[t]['worst_spread']:.2e})")

    print("\n=== P3: does breaking exchange symmetry break it at FIXED conservation "
          "structure?")
    for t in ("D", "E"):
        print(f"  {t}: {by[t]['cons_laws']} laws, {by[t]['exchange']:>13}  -> "
              f"{'HOLDS' if ok(t) else 'FAILS'}  (spread {by[t]['worst_spread']:.2e})")

    p2, p3 = ok("B") and ok("C"), (not ok("D")) and (not ok("E"))
    print("\n=== verdict")
    if gate and p2 and p3:
        print("  P4: the identity depends on EXCHANGE SYMMETRY, not on the number of")
        print("      conservation laws. B, D and E share the same conservation structure")
        print("      and differ only in whether the two recruitments mirror each other;")
        print("      C adds a third law and changes nothing. §30's claim is structural.")
    elif gate and not p2:
        print("  P5: an extra conservation law BREAKS the identity ->")
        print(f"      B {'holds' if ok('B') else 'fails'},"
              f" C {'holds' if ok('C') else 'fails'}. §30's reading is narrower than")
        print("      stated and does not reach multi-charge networks.")
    elif gate:
        print("  mixed: B and C hold but symmetry-breaking did NOT break the identity")
        print(f"      (D {'holds' if ok('D') else 'fails'},"
              f" E {'holds' if ok('E') else 'fails'}). Exchange symmetry is sufficient")
        print("      but not necessary, and the true condition is weaker than either.")
    else:
        print("  gate failed; verdict withheld.")

    print("\n=== P6: is the bracket actually different, or did nothing change?")
    for t in ("A", "B", "C"):
        r = by[t]
        if r["holds"]:
            print(f"  {t}: bracket spans {r['bracket_min']:.4f} .. {r['bracket_max']:.4f}"
                  f" over {r['n_states']} random states")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(rows, indent=2, default=float))
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
